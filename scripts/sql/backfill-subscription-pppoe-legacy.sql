DELIMITER $$

CREATE PROCEDURE pppoe_legacy_backfill_guard()
BEGIN
    DECLARE v_dups INT DEFAULT 0;
    SELECT COUNT(*) INTO v_dups
    FROM `subscription`
    WHERE `ip` = '192.168.26.199';
    IF v_dups > 1 THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Refuse PPPoE backfill: 192.168.26.199 maps to more than one subscription';
    END IF;
END$$

DELIMITER ;

CALL pppoe_legacy_backfill_guard();
